-- =========================================================================
-- رَصْد: قاعدة البيانات (Supabase / PostgreSQL)
-- جدول البلاغات + قيود التحقق + الصلاحيات (Row Level Security) + دالة إعادة البيانات التجريبية
-- =========================================================================

create table if not exists public.tickets (
  id           bigint generated by default as identity (start with 101) primary key,
  title        text not null check (char_length(title) between 1 and 120),
  description  text not null check (char_length(description) between 1 and 500),
  department   text not null check (department in ('تقنية المعلومات', 'الخدمات والصيانة', 'الشؤون الإدارية', 'المشاريع', 'خدمة المستفيدين')),
  priority     text not null default 'متوسطة' check (priority in ('عالية', 'متوسطة', 'منخفضة')),
  status       text not null default 'جديد' check (status in ('جديد', 'قيد المعالجة', 'منجز')),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  resolved_at  timestamptz,
  ai_dept      text,  -- الجهة التي اقترحها الذكاء الاصطناعي
  ai_priority  text   -- الأولوية التي اقترحها الذكاء الاصطناعي
);

-- فهارس لتسريع الفلترة والترتيب
create index if not exists tickets_status_idx on public.tickets (status);
create index if not exists tickets_department_idx on public.tickets (department);
create index if not exists tickets_created_idx on public.tickets (created_at desc);

-- تحديث وقت التعديل تلقائياً عند أي تغيير
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists tickets_touch on public.tickets;
create trigger tickets_touch before update on public.tickets
for each row execute function public.touch_updated_at();

-- الصلاحيات: تفعيل Row Level Security
-- نموذج تجريبي ببيانات افتراضية: يسمح للزائر بالقراءة والكتابة.
-- في النظام الحقيقي تُربط السياسات بتسجيل الدخول والصلاحيات (موظف / فني / مدير).
alter table public.tickets enable row level security;
grant select, insert, update, delete on public.tickets to anon;
grant usage, select on sequence public.tickets_id_seq to anon;
drop policy if exists "demo read" on public.tickets;
drop policy if exists "demo write" on public.tickets;
drop policy if exists "demo update" on public.tickets;
drop policy if exists "demo delete" on public.tickets;
create policy "demo read" on public.tickets for select to anon using (true);
create policy "demo write" on public.tickets for insert to anon with check (true);
create policy "demo update" on public.tickets for update to anon using (true) with check (true);
create policy "demo delete" on public.tickets for delete to anon using (true);

-- دالة لإعادة البيانات التجريبية: تفرّغ الجدول وتعيد الترقيم من 101
create or replace function public.reset_tickets() returns void
language sql security definer set search_path = public as $$
  truncate table public.tickets restart identity;
$$;
grant execute on function public.reset_tickets() to anon;
